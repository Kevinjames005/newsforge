import json

from fastapi import APIRouter, HTTPException, Response
from fastapi.responses import HTMLResponse

from app.database import repository as repo

router = APIRouter()


@router.get("/articles")
async def list_articles():
    return repo.list_articles()


@router.get("/articles/{article_id}")
async def get_article(article_id: str):
    article = repo.get_article(article_id)
    if not article:
        raise HTTPException(status_code=404, detail="Article not found")

    generated = repo.get_latest_generated(article_id)
    facts = repo.get_extracted_facts(article_id)
    fact_checks = []
    if generated:
        fact_checks = repo.get_fact_checks(generated["id"])
        # Ensure body is parsed from JSON string if needed
        if isinstance(generated.get("body"), str):
            try:
                generated["body"] = json.loads(generated["body"])
            except (json.JSONDecodeError, TypeError):
                pass
        if isinstance(generated.get("keywords"), str):
            try:
                generated["keywords"] = json.loads(generated["keywords"])
            except (json.JSONDecodeError, TypeError):
                pass

    return {
        "article": article,
        "generated": generated,
        "facts": facts,
        "fact_checks": fact_checks,
    }


@router.get("/articles/{article_id}/export")
async def export_article(article_id: str, format: str = "html"):
    article = repo.get_article(article_id)
    if not article:
        raise HTTPException(status_code=404, detail="Article not found")

    generated = repo.get_latest_generated(article_id)
    if not generated:
        raise HTTPException(status_code=404, detail="No generated article found")

    # Parse body
    body = generated.get("body", [])
    if isinstance(body, str):
        try:
            body = json.loads(body)
        except (json.JSONDecodeError, TypeError):
            body = []

    # Build simple HTML export
    headline = generated.get("headline", "Untitled")
    subheadline = generated.get("subheadline", "")
    lead = generated.get("lead", "")

    body_html = ""
    for para in body:
        if isinstance(para, str):
            body_html += f"<p>{para}</p>\n"
        elif isinstance(para, list):
            texts = " ".join(
                s.get("text", s) if isinstance(s, dict) else str(s) for s in para
            )
            body_html += f"<p>{texts}</p>\n"

    html = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{headline}</title>
<style>
  body {{ font-family: Georgia, serif; max-width: 700px; margin: 2rem auto; padding: 0 1rem; line-height: 1.8; color: #222; }}
  h1 {{ font-size: 2rem; line-height: 1.2; margin-bottom: 0.5rem; }}
  .sub {{ font-size: 1.2rem; color: #666; margin-bottom: 1rem; }}
  .lead {{ font-size: 1.1rem; font-weight: 500; margin-bottom: 1.5rem; }}
  .meta {{ font-size: 0.85rem; color: #999; margin-bottom: 2rem; }}
</style>
</head>
<body>
<h1>{headline}</h1>
{"<p class='sub'>" + subheadline + "</p>" if subheadline else ""}
{"<p class='lead'>" + lead + "</p>" if lead else ""}
<p class="meta">Generated by NewsForge AI &bull; {article.get("target_language", "")} &bull; {article.get("style", "")}</p>
{body_html}
</body>
</html>"""

    return Response(
        content=html,
        media_type="text/html",
        headers={"Content-Disposition": f'attachment; filename="{headline[:50]}.html"'},
    )
